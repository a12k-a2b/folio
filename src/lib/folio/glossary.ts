const BY_KEY = new Map(GLOSS_ENTRIES.map((e) => [e.key, e]));

function normalize(word: string): string {
  return word.toLowerCase().replace(/[^a-z]/g, "");
}

export function glossEntry(word: string): GlossEntry | null {
  const key = normalize(word);
  if (!key) return null;
  if (BY_KEY.has(key)) return BY_KEY.get(key) ?? null;
  for (const e of GLOSS_ENTRIES) {
    if (e.key.startsWith(key) || key.startsWith(e.key)) return e;
    if (normalize(e.word) === key) return e;
  }
  return null;
}

export function glossFor(word: string): string | null {
  const e = glossEntry(word);
  return e ? e.short : null;
}

export function termsInText(text: string): GlossEntry[] {
  const lower = text.toLowerCase();
  const out: GlossEntry[] = [];
  const seen = new Set<string>();
  const sorted = [...GLOSS_ENTRIES].sort((a, b) => b.word.length - a.word.length);
  for (const e of sorted) {
    const re = new RegExp(`\\b${escapeRe(e.word)}\\b`, "i");
    if (re.test(lower) && !seen.has(e.key)) {
      seen.add(e.key);
      out.push(e);
    }
  }
  return out;
}

const KNOWN_KEY = "folio.knownGloss";

export function loadKnownGloss(): Set<string> {
  try {
    const raw = localStorage.getItem(KNOWN_KEY);
    if (!raw) return new Set();
    const arr = JSON.parse(raw) as string[];
    return new Set(arr);
  } catch {
    return new Set();
  }
}

export function saveKnownGloss(keys: Set<string>) {
  try {
    localStorage.setItem(KNOWN_KEY, JSON.stringify([...keys]));
  } catch {
    /* ignore */
  }
}

export function wrapGlossHtml(html: string, known: Set<string>): string {
  const entries = [...GLOSS_ENTRIES]
    .filter((e) => !known.has(e.key))
    .sort((a, b) => b.word.length - a.word.length);

  return html.replace(/(<[^>]+>)|([^<]+)/g, (full, tag: string | undefined, text: string | undefined) => {
    if (tag || !text) return tag || full;
    type Hit = { start: number; end: number; word: string; key: string };
    const hits: Hit[] = [];
    for (const e of entries) {
      const re = new RegExp(`\\b${escapeRe(e.word)}\\b`, "gi");
      let m: RegExpExecArray | null;
      while ((m = re.exec(text))) {
        const start = m.index;
        const end = start + m[0].length;
        if (hits.some((h) => !(end <= h.start || start >= h.end))) continue;
        hits.push({ start, end, word: m[0], key: e.key });
      }
    }
    hits.sort((a, b) => a.start - b.start);
    let out = "";
    let cursor = 0;
    for (const h of hits) {
      out += text.slice(cursor, h.start);
      out += `<span class="gterm" data-g="${h.key}">${h.word}</span>`;
      cursor = h.end;
    }
    return out + text.slice(cursor);
  });
}

function escapeRe(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}
